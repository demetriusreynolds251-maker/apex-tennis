def _due(key, at, ok_day, now=None):
    now = now or datetime.now(CT)
    if not ok_day(now) or (now.hour, now.minute) < at:
        return False
    return _state().get(key) != now.date().isoformat()


def weekly_due(now=None):
    return _due("weekly_posted", WEEKLY_AT, lambda n: n.weekday() == 0, now)


def monthly_due(now=None):
    return _due("monthly_posted", MONTHLY_AT, lambda n: n.day == 1, now)


def mark_posted(key, now=None):
    now = now or datetime.now(CT)
    st = _state()
    st[key] = now.date().isoformat()
    st["at"] = now.isoformat(timespec="seconds")
    os.makedirs(os.path.dirname(STATE), exist_ok=True)
    with open(STATE + ".tmp", "w") as fh:
        json.dump(st, fh)
    os.replace(STATE + ".tmp", STATE)


QUEUE = os.path.join(HERE, "data", "logs", "pnl_post_queue.json")


def queue_post(kind="daily", day=None):
    """Asks the running bot to post a card to #pnl within a minute (python3 apex_pnl_channel.py post week)."""
    q = take_post_queue(clear=False)
    q.append({"kind": kind, "day": day})
    with open(QUEUE + ".tmp", "w") as fh:
        json.dump(q, fh)
    os.replace(QUEUE + ".tmp", QUEUE)


def take_post_queue(clear=True):
    try:
        with open(QUEUE) as fh:
            q = json.load(fh)
    except Exception:
        return []
    if clear:
        os.remove(QUEUE)
    return q if isinstance(q, list) else []


def last_week_day(now=None):
    """Any day of last week (for the Monday post)."""
    return ((now or datetime.now(CT)).date() - timedelta(days=7)).isoformat()


def last_month_day(now=None):
    return ((now or datetime.now(CT)).date().replace(day=1) - timedelta(days=1)).isoformat()


