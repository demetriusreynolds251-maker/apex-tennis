    tiles.append({"name": "📈 %s so far %s" % (b["day"][:4], _dot(b["ta"]["net"])), "value": _box(b["ta"]), "inline": True})
    if len(tiles) == 4:   # 2 x 2 instead of 3 + 1
        tiles.insert(2, {"name": "​", "value": "​", "inline": True})
    fields = list(tiles)
    if b["best"]:
        fields.append({"name": "🏆 Best slip", "value": b["best"], "inline": False})
    if b["worst"]:
        fields.append({"name": "💔 Costliest miss", "value": b["worst"], "inline": False})
