def refuse_reason(sid, legs):
    """None for a real slip he logged, else why it is kept out of the money."""
    if not _SID.match(str(sid or "")):
        return "slip id %r is not a logged-slip id" % sid
    for l in legs:
        if not l.get("raw_text") or not l.get("logged_at"):
            return "leg without raw_text/logged_at (not from slip intake)"
        if any(l.get(k) for k in _APEX_KEYS):
            return "marked as an Apex slip"
        txt = " ".join(str(l.get(k) or "") for k in ("raw_text", "source", "pp_note", "logged_at", "entry_type")).lower()
        w = next((w for w in _APEX_WORDS if w in txt), None)
        if w:
            return "Apex slip wording (%r)" % w
        if str(l.get("book") or "prizepicks").lower() != "prizepicks":
            return "book %r is not PrizePicks" % l.get("book")
    return None


def _log_refused(items):
    """Overwrites pnl/refused_rows.json with what the last read kept out (empty list = nothing)."""
    try:
        os.makedirs(os.path.dirname(REFUSED), exist_ok=True)
        old = None
        try:
            with open(REFUSED) as fh:
                old = json.load(fh).get("refused")
        except Exception:
            pass
        if old != items:
            with open(REFUSED + ".tmp", "w") as fh:
                json.dump({"at": datetime.now(CT).isoformat(timespec="seconds"), "refused": items}, fh, indent=1)
            os.replace(REFUSED + ".tmp", REFUSED)
            for it in items:
                print("[PnL] refused %s: %s" % (it["slip_id"], it["why"]))
    except Exception:
        pass


def _real_groups(rows):
    by = OrderedDict()
    for r in rows:
        by.setdefault(r.get("slip_id"), []).append(r)
    ok, bad = OrderedDict(), []
    for sid, legs in by.items():
        why = refuse_reason(sid, legs)
        if why:
            bad.append({"slip_id": str(sid), "date": str(legs[0].get("date") or "")[:10], "why": why})
        else:
            ok[sid] = legs
    _log_refused(bad)
    return ok


def slips():
    """[slip dict] -- one per slip_id: date, stake, back, net, result, entry, legs."""
    try:
        with open(LEDGER) as fh:
            rows = json.load(fh)
    except Exception:
        return []
    out = []
    for sid, legs in _real_groups(rows).items():
        r = legs[0]
        res = str(r.get("slip_result") or "").upper()
        if res not in ("WON", "LOST", "PUSH", "VOID"):
            continue   # still open -- counted once it is finished
        stake = float(r.get("stake") or 0)
        net = float(r.get("slip_profit") or 0)
        out.append({"id": sid, "date": str(r.get("date") or "")[:10], "stake": stake, "back": stake + net,
                    "net": net, "result": res, "entry": r.get("entry_type") or "slip",
                    "bonus": "bonus" in str(r.get("entry_type") or "").lower(), "no": r.get("real_slip_no"),
                    "legs": legs})
    return out


def confirm_in_app():
    """APEX-VOIDGRADE-2026-10-24: finished slips whose payout PrizePicks re-priced (a push or
    void, or a Flex that paid part) -- won or paid, but the amount is only in the app, so
    they are listed on the card and left out of the money until the app amount is set."""
    try:
        with open(LEDGER) as fh:
            rows = json.load(fh)
    except Exception:
        return []
    by = OrderedDict()
    for sid, legs in _real_groups(rows).items():
        r = legs[0]
        if str(r.get("slip_result") or "").upper() in ("WON_WITH_PUSH", "CHECK_APP"):
            by.setdefault(sid, r)
    out = []
    for r in by.values():
        if str(r.get("date") or "")[:10] < SINCE:
            continue
        no = ("#%s " % r["real_slip_no"]) if r.get("real_slip_no") else ""
        what = "won" if str(r.get("slip_result")).upper() == "WON_WITH_PUSH" else "paid part"
        out.append("🟡 %s%s, $%.2f entry, %s -- %s, confirm the payout in the app" % (
            no, r.get("entry_type") or "slip", float(r.get("stake") or 0), _short(str(r.get("date"))[:10]), what))
    return out


def _sum(ss):
    n = len(ss)
    stake = sum(s["stake"] for s in ss)
    back = sum(s["back"] for s in ss)
    won = sum(s["net"] > 0.004 for s in ss)
    return {"n": n, "won": won, "in": stake, "back": back, "net": back - stake,
            "roi": ((back - stake) / stake * 100) if stake else None}


def _who(l):
    nm = str(l.get("player") or "?")
    return nm.split()[-1] if " " in nm else nm


def _leg_words(l):
    stat = str(l.get("stat_label") or l.get("stat_type") or "").replace("_", " ")
    stat = {"total games": "Total Games", "fantasy score": "Fantasy", "double faults": "Double Faults",
            "aces": "Aces"}.get(stat, stat.title() if stat.islower() else stat)
    line = l.get("line")
    line = ("%g" % line) if isinstance(line, (int, float)) else str(line)
    return "%s %s %s %s" % (l.get("player"), stat, str(l.get("direction") or "").upper(), line)


def best_slip(ss):
    if not ss:
        return None
    s = max(ss, key=lambda s: (s["net"], s["back"]))
    hit = sum(str(l.get("status")).upper() == "WIN" for l in s["legs"])
    n = sum(str(l.get("status")).upper() in ("WIN", "LOSS") for l in s["legs"])
    return "%s %s on %s → paid %s (%s) · %d of %d hit" % (
        _plain(s["stake"]) if not s["bonus"] else "Bonus", s["entry"], _short(s["date"]),
        _plain(s["back"]), _money(s["net"]), hit, n)


def worst_leg(ss):
    """The losing leg that cost the most: the money riding on the slips it sat on."""
    cost = defaultdict(lambda: [0, 0.0, None])
    for s in ss:
        for l in s["legs"]:
            if str(l.get("status")).upper() != "LOSS":
                continue
            k = (l.get("player"), l.get("stat_type"), l.get("line"), l.get("direction"))
            c = cost[k]
            c[0] += 1; c[1] += s["stake"]; c[2] = l
    if not cost:
        return None
    n, money, l = max(cost.values(), key=lambda c: (c[1], c[0]))
    act = l.get("actual")
    act = (" (finished at %g)" % act) if isinstance(act, (int, float)) else ""
    return "%s%s · missed on %d slip%s, %s riding" % (_leg_words(l), act, n, "" if n == 1 else "s", _plain(money))


def sparkline(ss, day, n=SPARK_DAYS):
    end = datetime.strptime(day, "%Y-%m-%d").date()
    days = [(end - timedelta(days=i)).isoformat() for i in range(n - 1, -1, -1)]
    net = defaultdict(float); played = set()
    for s in ss:
        net[s["date"]] += s["net"]; played.add(s["date"])
    vals = [net[d] for d in days]
    top = max([abs(v) for v in vals] + [1])
    bars = "".join((BARS[min(len(BARS) - 1, int(abs(v) / top * (len(BARS) - 1) + 0.5))] if d in played else " ")
                   for d, v in zip(days, vals))
    dots = "".join(_dot(net[d]) if d in played else "⚫" for d in days)
    return bars, dots, days


