def build(day=None):
    day = day or yesterday()
    ss = [s for s in slips() if s["date"] >= SINCE]
    today = [s for s in ss if s["date"] == day]
    d0 = datetime.strptime(day, "%Y-%m-%d").date()
    wk0 = (d0 - timedelta(days=d0.weekday())).isoformat()
    week = [s for s in ss if wk0 <= s["date"] <= day]
    month = [s for s in ss if s["date"][:7] == day[:7] and s["date"] <= day]
    since = [s for s in ss if s["date"] <= day]
    year = [s for s in since if s["date"][:4] == day[:4]]
    td, tw, tm, ty = _sum(today), _sum(week), _sum(month), _sum(year)
    bars, dots, days = sparkline(since, day)
    return {"day": day, "today": today, "td": td, "tw": tw, "tm": tm, "ta": ty, "week_from": wk0,
            "best": best_slip(today), "worst": worst_leg(today), "bars": bars, "dots": dots, "spark_days": days}


